"""The Phase 5 diff audit: the leak test, made mechanical.

Phase 5's claim is that a second backend arrived without the layers
above the backend line changing. That claim is not a matter of opinion:
this script diffs the working tree against the Phase 4 commit and
fails if any file outside the allow-list below changed. The allow-list
*is* the test's substance, so it is kept minimal and every entry carries
its reason:

- The new backend module and its registration machinery — the phase
  itself.
- The registration seam: the exact existing files that had to change so
  a backend can be *registered* — the composition root's default
  wiring, the candidate generator's search space, the estimator's
  per-backend constants, and the package's docstring/exports. Each is
  a place where a backend's existence or data is declared, not a place
  where planning, policy, execution, or recording *judgment* lives.
- Tests, guide, README, and the regenerated evidence — documentation
  and proof are part of every phase's done-criteria.

Everything else — the planner, the scorer, the executor, the policy
engine, the workload contract, the telemetry shapes, the receipt, the
CPU backend, the model registry, the transformation and quality
services — must be byte-identical to Phase 4. If this audit fails, the
abstraction leaked, and the failure output is the finding.

Usage: .venv/bin/python phase5_diff_audit.py [phase4-commit]
Exit code 0 = PASS, 1 = FAIL.
"""
import subprocess
import sys

PHASE4_COMMIT = "19701d54c5676c4d8b948ba284ef69a26bda2145"

NEW_FILES = {
    "aacl/backends/gpu.py": "the GPU backend itself",
    "aacl/backends/discovery.py": "backend discovery/registration",
    "aacl/backends/router.py": "dispatch across the registered backends",
    "phase5_demo.py": "the Phase 5 demonstration",
    "phase5_diff_audit.py": "this audit",
    "docs/phase5-strix-runbook.md": "the hardware session's runbook",
}

MODIFIED_FILES = {
    "aacl/api/service.py": "composition root: the default backend "
                           "becomes the registered set (registration seam)",
    "aacl/planner/candidate_generator.py": "candidate generation "
                           "enumerates the registry when the profile is "
                           "registered (registration seam)",
    "aacl/planner/estimates.py": "the GPU's static estimate constants "
                           "register where the estimate model lives "
                           "(registration seam)",
    "aacl/__init__.py": "package docstring + public exports, as in "
                        "every prior phase",
    "test_aacl.py": "Phase 5 tests + three adaptations whose counts "
                    "are relative to the registry (reasons in place)",
    "docs/guide.md": "the Phase 5 section",
    "README.md": "the Phase 5 status",
}

EVIDENCE_PREFIX = "evidence/"  # regenerated by prove.py, as every phase

PROTECTED_EXAMPLES = [
    "aacl/planner/planner.py", "aacl/planner/scorer.py",
    "aacl/planner/explain.py", "aacl/core/executor.py",
    "aacl/core/workload.py", "aacl/core/execution.py",
    "aacl/core/failures.py", "aacl/core/capabilities.py",
    "aacl/policy/", "aacl/telemetry/", "aacl/backends/base.py",
    "aacl/backends/cpu.py", "aacl/models/", "aacl/optimization/",
    "prove.py",
]


def _git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True,
                          check=True).stdout


def changed_paths(commit):
    """path -> status letter, for everything that differs from the
    Phase 4 commit: tracked changes plus untracked files."""
    changes = {}
    out = _git("diff", "--name-status", "--no-renames", commit, "--")
    for line in out.splitlines():
        if not line.strip():
            continue
        status, path = line.split("\t", 1)
        changes[path] = status[0]
    for path in _git("ls-files", "--others", "--exclude-standard").splitlines():
        if path:
            changes.setdefault(path, "A")
    return changes


def main():
    commit = sys.argv[1] if len(sys.argv) > 1 else PHASE4_COMMIT
    try:
        full = _git("rev-parse", commit).strip()
    except subprocess.CalledProcessError:
        print(f"FAIL: cannot resolve Phase 4 commit {commit!r}")
        return 1
    changes = changed_paths(commit)
    violations = []
    allowed = []
    for path, status in sorted(changes.items()):
        if path.startswith(EVIDENCE_PREFIX):
            allowed.append((path, status, "regenerated evidence"))
        elif status == "A" and path in NEW_FILES:
            allowed.append((path, status, NEW_FILES[path]))
        elif status == "M" and path in MODIFIED_FILES:
            allowed.append((path, status, MODIFIED_FILES[path]))
        else:
            violations.append((path, status))
    print(f"Diff audit against Phase 4 ({full[:12]}): "
          f"{len(changes)} changed path(s)")
    for path, status, reason in allowed:
        print(f"  allowed [{status}] {path} — {reason}")
    for path, status in violations:
        print(f"  VIOLATION [{status}] {path} — outside the Phase 5 allow-list")
    print("Protected, and required to be byte-identical: "
          + ", ".join(PROTECTED_EXAMPLES) + ", …")
    if violations:
        print(f"FAIL: {len(violations)} file(s) outside the allow-list. "
              f"The abstraction leaked; this output is the finding.")
        return 1
    print("PASS: every change is inside the Phase 5 allow-list; the "
          "non-backend layers are byte-identical to Phase 4.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
